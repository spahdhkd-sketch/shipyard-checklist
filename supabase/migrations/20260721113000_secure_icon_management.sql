  category_id, previous_icon, next_icon, action, changed_by_worker_name
)
select id, 'C', 'safetyGear', 'migration', 'system:migration'
from changed;

with selected as (
  select id
  from public.safety_pictograms
  where label = 'DCP'
    and source = 'custom'
    and not deleted
  order by sort_order desc, id desc
  limit 1
), changed as (
  update public.safety_categories
  set icon = selected.id,
      updated_at = now()
  from selected
  where safety_categories.id = 'ra_std07'
    and safety_categories.icon = 'D'
  returning safety_categories.id, selected.id as next_icon
)
insert into public.safety_icon_change_history (
  category_id, previous_icon, next_icon, action, changed_by_worker_name
)
select id, 'D', next_icon, 'migration', 'system:migration'
from changed;

update public.safety_pictograms
set src = '',
    updated_at = now()
where deleted
  and src <> '';

